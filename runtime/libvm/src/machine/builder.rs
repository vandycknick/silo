/// Builder for creating a machine.
///
/// The builder records durable desired configuration. It does not start silo-vmm or
/// prepare networking. Those runtime artifacts are regenerated by `Machine::start`.
/// Image materialization happens during `create`; `Machine::start` only boots the
/// already-created root disk.
///
/// ```rust,no_run
/// use libvm::{ImageSource, Memory, Runtime};
///
/// # async fn example(runtime: Runtime) -> Result<(), libvm::LibVmError> {
/// let machine = runtime
///     .machine()
///     .image("docker.io/library/alpine:latest")
///     .name("devbox")
///     .cpus(4)
///     .memory(Memory::gibibytes(8))
///     .network(|network| network.private())
///     .create()
///     .await?;
/// let from_disk = runtime
///     .machine()
///     .image_source(ImageSource::disk("/tmp/root.raw"))
///     .create()
///     .await?;
/// # let _ = from_disk;
/// # let _ = machine;
/// # Ok(())
/// # }
/// ```
pub struct MachineBuilder {
    runtime: Runtime,
    request: MachineCreateRequest,
}

impl MachineBuilder {
    pub(crate) fn new(runtime: Runtime) -> Self {
        Self {
            runtime,
            request: MachineCreateRequest {
                image_source: None,
                resolved_oci_image: None,
                name: None,
                labels: BTreeMap::new(),
                metadata: BTreeMap::new(),
                cpus: None,
                memory: None,
                kernel: None,
                initramfs: None,
                kernel_args: Vec::new(),
                disk_size_bytes: None,
                root_profile: RootProfile::OpaqueRaw,
                temporary_directory: crate::TemporaryDirectoryPolicy::DiskBacked,
                nested_virtualization: false,
                rosetta: false,
                userdata: None,
                disks: Vec::new(),
                mounts: Vec::new(),
                forwards: Vec::new(),
                vsock: None,
                network: None,
                network_error: None,
                guest: MachineGuestConfig::default(),
                retention: MachineRetention::Persistent,
                process: ProcessConfig::default(),
                template_name: None,
                agent_mode: None,
            },
        }
    }

    /// Selects an OCI image reference for this machine.
    ///
    /// The string is always interpreted as OCI. Use `image_source` or
    /// `image_with` for local disk sources.
    pub fn image(mut self, reference: impl Into<String>) -> Self {
        self.request.image_source = Some(ImageSource::oci(reference));
        self.request.resolved_oci_image = None;
        self
    }

    /// Selects an explicit image source.
    pub fn image_source(mut self, source: ImageSource) -> Self {
        self.request.image_source = Some(source);
        self.request.resolved_oci_image = None;
        self
    }

    /// Selects an image source using a dedicated image builder.
    pub fn image_with(mut self, configure: impl FnOnce(ImageBuilder) -> ImageBuilder) -> Self {
        self.request.image_source = configure(ImageBuilder::new()).finish();
        self.request.resolved_oci_image = None;
        self
    }

    /// Uses an immutable OCI selection returned by `Runtime::images().resolve`.
    ///
    /// Creation materializes this exact selection and never resolves the original
    /// mutable reference again.
    pub fn resolved_image(mut self, image: ResolvedOciImage) -> Self {
        self.request.image_source = Some(ImageSource::oci(image.requested_reference.clone()));
        self.request.resolved_oci_image = Some(image);
        self
    }

    /// Selects root storage explicitly; opaque raw remains the default.
    pub fn root_profile(mut self, profile: RootProfile) -> Self {
        self.request.root_profile = profile;
        self
    }

    /// Selects persistent disk-backed `/tmp` or an explicitly sized tmpfs.
    pub fn temporary_directory(mut self, policy: crate::TemporaryDirectoryPolicy) -> Self {
        self.request.temporary_directory = policy;
        self
    }

    /// Sets an explicit machine name.
    pub fn name(mut self, name: impl Into<String>) -> Self {
        self.request.name = Some(name.into());
        self
    }

    /// Replaces all labels.
    pub fn labels(mut self, labels: BTreeMap<String, String>) -> Self {
        self.request.labels = labels;
        self
    }

    /// Adds one label.
    pub fn label(mut self, key: impl Into<String>, value: impl Into<String>) -> Self {
        self.request.labels.insert(key.into(), value.into());
        self
    }

    /// Replaces all metadata.
    pub fn metadata(mut self, metadata: BTreeMap<String, String>) -> Self {
        self.request.metadata = metadata;
        self
    }

    /// Adds one metadata entry.
    pub fn metadata_entry(mut self, key: impl Into<String>, value: impl Into<String>) -> Self {
        self.request.metadata.insert(key.into(), value.into());
        self
    }

    /// Sets the virtual CPU count.
    pub fn cpus(mut self, cpus: u8) -> Self {
        self.request.cpus = Some(cpus);
        self
    }

    /// Sets the machine memory.
    pub fn memory(mut self, memory: Memory) -> Self {
        self.request.memory = Some(memory);
        self
    }

    /// Sets a kernel path override.
    pub fn kernel(mut self, kernel: impl Into<PathBuf>) -> Self {
        self.request.kernel = Some(kernel.into());
        self
    }

    /// Sets an initramfs path override.
    pub fn initramfs(mut self, initramfs: impl Into<PathBuf>) -> Self {
        self.request.initramfs = Some(initramfs.into());
        self
    }

    /// Replaces the extra Linux kernel command-line arguments.
    pub fn kernel_args(mut self, args: Vec<String>) -> Self {
        self.request.kernel_args = args;
        self
    }

    /// Configures durable guest behavior outside the VMM specification.
    pub fn guest(mut self, configure: impl FnOnce(GuestBuilder) -> GuestBuilder) -> Self {
        self.request.guest = configure(GuestBuilder::new()).build();
        self
    }

    /// Sets the machine retention policy.
    pub fn retention(mut self, retention: MachineRetention) -> Self {
        self.request.retention = retention;
        self
    }

    /// Replaces durable process settings.
    pub fn process(mut self, process: ProcessConfig) -> Self {
        self.request.process = process;
        self
    }

    /// Sets the durable OCI entrypoint, preserving unset and empty values distinctly.
    pub fn entrypoint(mut self, entrypoint: Option<Vec<String>>) -> Self {
        self.request.process.entrypoint = entrypoint;
        self
    }

    /// Sets the durable OCI command, preserving unset and empty values distinctly.
    pub fn command(mut self, command: Option<Vec<String>>) -> Self {
        self.request.process.command = command;
        self
    }

    /// Replaces the deterministic process environment.
    pub fn environment(mut self, environment: BTreeMap<String, String>) -> Self {
        self.request.process.environment = environment;
        self
    }

    /// Sets the durable process working directory.
    pub fn working_directory(mut self, working_directory: impl Into<String>) -> Self {
        self.request.process.working_directory = working_directory.into();
        self
    }

    /// Sets the durable optional OCI-style process user selector.
    pub fn process_user(mut self, user: Option<String>) -> Self {
        self.request.process.user = user;
        self
    }

    /// Records the selected machine template.
    pub fn template_name(mut self, template_name: Option<String>) -> Self {
        self.request.template_name = template_name;
        self
    }

    /// Records an explicit agent mode independently of current guest launch behavior.
    pub fn agent_mode(mut self, agent_mode: Option<MachineAgent>) -> Self {
        self.request.agent_mode = agent_mode;
        self
    }

    /// Sets the desired root disk size in bytes.
    pub fn root_disk_size(mut self, bytes: u64) -> Self {
        self.request.disk_size_bytes = Some(bytes);
        self
    }

    /// Enables or disables nested virtualization.
    pub fn nested_virtualization(mut self, enabled: bool) -> Self {
        self.request.nested_virtualization = enabled;
        self
    }

    /// Enables or disables Rosetta support.
    pub fn rosetta(mut self, enabled: bool) -> Self {
        self.request.rosetta = enabled;
        self
    }

    /// Sets guest userdata.
    pub fn userdata(mut self, userdata: impl Into<String>) -> Self {
        self.request.userdata = Some(userdata.into());
        self
    }

    /// Replaces additional disk paths.
    pub fn disks(mut self, disks: Vec<PathBuf>) -> Self {
        self.request.disks = disks;
        self
    }

    /// Replaces guest mounts.
    pub fn mounts(mut self, mounts: Vec<Mount>) -> Self {
        self.request.mounts = mounts;
        self
    }

    /// Replaces the machine-scoped forwards activated on every machine start.
    pub fn forwards(mut self, forwards: Vec<forward_spec::Forward>) -> Self {
        self.request.forwards = forwards;
        self
    }

    /// Enables or disables the public vsock surface with its default socket name.
    pub fn vsock(mut self, enabled: bool) -> Self {
        self.request.vsock = Some(vm_spec::Vsock { enabled, uds: None });
        self
    }

    /// Configures the durable network attachment.
    pub fn network(
        mut self,
        configure: impl FnOnce(MachineNetworkBuilder) -> MachineNetworkBuilder,
    ) -> Self {
        match configure(MachineNetworkBuilder::new()).build() {
            Ok(network) => self.request.network = Some(network),
            Err(reason) => self.request.network_error = Some(reason),
        }
        self
    }

    /// Creates the machine.
    pub async fn create(self) -> Result<Machine, LibVmError> {
        let runtime = self.runtime;
        let handle = tokio::runtime::Handle::current();
        let worker_runtime = runtime.clone();
        let config = tokio::task::spawn_blocking(move || {
            handle.block_on(create_machine_config(&worker_runtime, self.request))
        })
        .await??;
        Ok(Machine::new(runtime.without_image_progress(), config.id))
    }
}

async fn create_machine_config(
    runtime: &Runtime,
    request: MachineCreateRequest,
) -> Result<MachineConfig, LibVmError> {
    let Some(name) = request.name.clone() else {
        return create_machine_config_with_generated_name(runtime, request).await;
    };

    create_machine_config_with_name(runtime, request, name).await
}

async fn create_machine_config_with_generated_name(
    runtime: &Runtime,
    request: MachineCreateRequest,
) -> Result<MachineConfig, LibVmError> {
    for _ in 0..GENERATED_NAME_ATTEMPTS {
        let name = generate_machine_name()?;
        match create_machine_config_with_name(runtime, request.clone(), name).await {
            Err(LibVmError::MachineAlreadyExists { .. }) => {}
            result => return result,
        }
    }

    Err(LibVmError::MachineNameGenerationFailed {
        attempts: GENERATED_NAME_ATTEMPTS,
    })
}

async fn create_machine_config_with_name(
    runtime: &Runtime,
    mut request: MachineCreateRequest,
    name: String,
) -> Result<MachineConfig, LibVmError> {
    if matches!(request.disk_size_bytes, Some(0)) {
        return Err(LibVmError::InvalidCreateRequest {
            name,
            reason: "root disk size must be greater than 0".to_string(),
        });
    }
    crate::machine::reference::validate_new_machine_name(&name)?;
    if matches!(request.cpus, Some(0)) {
        return Err(LibVmError::InvalidCreateRequest {
            name,
            reason: "cpus must be greater than 0".to_string(),
        });
    }
    let Some(image_source) = request.image_source.clone() else {
        return Err(LibVmError::InvalidCreateRequest {
            name,
            reason: "machine image source is required".to_string(),
        });
    };
    if let Some(reason) = request.network_error {
        return Err(LibVmError::InvalidCreateRequest { name, reason });
    }
    if let Some(user) = &request.guest.user {
        user.validate()
            .map_err(|reason| LibVmError::InvalidCreateRequest {
                name: name.clone(),
                reason,
            })?;
    }

    let (kernel, initramfs) = crate::runtime::boot_assets::canonicalize_boot_overrides(
        crate::runtime::boot_assets::BootAssetOverrides {
            kernel: request.kernel.as_deref(),
            initramfs: request.initramfs.as_deref(),
        },
    )?;
    request.guest = crate::runtime::boot_assets::canonicalize_guest_config(request.guest)?;
    if let Some(userdata) = request.userdata.as_deref() {
        if userdata.trim().is_empty() {
            return Err(LibVmError::InvalidCreateRequest {
                name,
                reason: "userdata cannot be empty".to_string(),
            });
        }
    }
    let userdata = request.userdata;
    let disk_paths = canonicalize_existing_paths(&request.disks, "disk")?;

    let resolved_cpus = request.cpus.unwrap_or(DEFAULT_IMAGE_CPUS);
    let resolved_memory = request
        .memory
        .map(|memory| memory.to_vm_spec_mebibytes(&name))
        .transpose()?
        .unwrap_or(DEFAULT_IMAGE_MEMORY_MIB);

    let overlay = request.root_profile == RootProfile::LinuxFlatOverlayV1;
    if overlay {
        if !matches!(&image_source, ImageSource::Oci(_)) {
            return Err(LibVmError::InvalidCreateRequest {
                name,
                reason: "flat overlay requires an OCI image source".into(),
            });
        }
        if request.kernel_args.iter().any(|arg| {
            ["root=", "rootfstype=", "rootflags=", "silo.rootfs="]
                .iter()
                .any(|key| arg.starts_with(key))
        }) {
            return Err(LibVmError::InvalidCreateRequest {
                name,
                reason: "flat overlay forbids conflicting root-selection arguments".into(),
            });
        }
        rootfs_spec::upper_geometry::UpperCapacity::new(
            request.disk_size_bytes.unwrap_or(4 * 1024 * 1024 * 1024),
        )
        .map_err(|error| LibVmError::InvalidCreateRequest {
            name: name.clone(),
            reason: error.to_string(),
        })?;
        request.temporary_directory.validate()?;
        crate::storage::limits::Resource::IncludedDisks
            .sum([2, disk_paths.len() as u64])
            .map_err(crate::storage::StorageError::from)?;
        runtime.qualify_flat_overlay(kernel.as_deref(), initramfs.as_deref())?;
    } else if request.temporary_directory != crate::TemporaryDirectoryPolicy::DiskBacked {
        return Err(LibVmError::InvalidCreateRequest {
            name,
            reason: "temporary-directory policy requires flat overlay".into(),
        });
    }
    let mounts = assign_mount_tags(request.mounts);
    let kernel_cmdline = if overlay {
        std::iter::once("silo.rootfs=linux-flat-overlay-v1".to_string())
            .chain(request.kernel_args)
            .collect()
    } else {
        build_kernel_cmdline(request.kernel_args)
    };
    let mut disks = if overlay {
        vec![
            crate::machine::root_storage::disk(
                "lower.vmdk",
                vm_spec::DiskRole::RootLower,
                512,
                "silo-root-lower".into(),
            )?,
            crate::machine::root_storage::disk(
                "upper.raw",
                vm_spec::DiskRole::RootUpper,
                request.disk_size_bytes.unwrap_or(4 * 1024 * 1024 * 1024),
                "silo-root-upper".into(),
            )?,
        ]
    } else {
        vec![crate::machine::root_storage::disk(
            root_disk_relative_path(),
            vm_spec::DiskRole::Root,
            512,
            "silo-root".into(),
        )?]
    };
    for (index, path) in disk_paths.into_iter().enumerate() {
        let length = std::fs::metadata(&path)?.len();
        disks.push(crate::machine::root_storage::disk(
            path,
            vm_spec::DiskRole::Data,
            length,
            format!("silo-data-{index}"),
        )?);
    }

    let spec = VmSpec {
        guest: Some(Guest {
            os: Some(GuestOs::Linux),
        }),
        boot: Some(Boot {
            kernel: Some(Kernel {
                path: kernel,
                cmdline: kernel_cmdline,
                initramfs,
            }),
            userdata,
        }),
        hardware: Some(Hardware {
            cpus: Some(resolved_cpus),
            memory: Some(resolved_memory),
            nested_virtualization: Some(request.nested_virtualization),
            rosetta: Some(request.rosetta),
        }),
        storage: Some(Storage { disks }),
        mounts,
        vsock: request.vsock,
        forwards: request.forwards,
        ..VmSpec::current()
    };
    spec.validate()
        .map_err(|error| LibVmError::InvalidMachineConfig {
            reference: name.clone(),
            reason: error.to_string(),
        })?;

    let network = request.network.unwrap_or_default().into();
    runtime.validate_machine_network_config(&network).await?;
    let tailscale = runtime.validate_tailscale_vsock(&network, &spec)?;
    let materialized = match request.resolved_oci_image.as_ref() {
        Some(image) => runtime.materialize_resolved_oci_image(image).await?,
        None => runtime.materialize_image(&image_source).await?,
    };
    let _name_lock = runtime.lock_machine_names().await?;
    let mut create = create_machine_guard(
        runtime,
        MachineCreatePlan {
            name,
            spec,
            labels: request.labels,
            metadata: request.metadata,
            network,
            guest: request.guest,
            retention: request.retention,
            process: request.process,
            template_name: request.template_name,
            agent_mode: request.agent_mode,
        },
        None,
    )
    .await?;

    if tailscale {
        runtime.ensure_tailscale_directory(create.id)?;
    }
    let root_disk_size = request.disk_size_bytes.unwrap_or(if overlay {
        4 * 1024 * 1024 * 1024
    } else {
        materialized.size_bytes
    });
    crate::storage::limits::validate_disk_length(root_disk_size)
        .map_err(crate::storage::StorageError::from)?;
    let (rootfs_path, storage) = if overlay {
        let stream = materialized.stream.ok_or_else(|| {
            crate::machine::root_storage::invalid(
                "materialized OCI base has no retained stream identity",
            )
        })?;
        let lower_uuid = crate::machine::root_storage::filesystem_uuid(&materialized.rootfs_path)?;
        let rootfs_path = create.dir().join("upper.raw");
        let capacity = rootfs_spec::upper_geometry::UpperCapacity::new(root_disk_size)
            .map_err(|error| crate::machine::root_storage::invalid(error.to_string()))?;
        let formatted = disk_image::ext4::upper::format_upper(&rootfs_path, capacity)?;
        let mut storage = crate::MachineStorageRecord::opaque_raw(
            crate::PrivatePath::new("upper.raw")?,
            root_disk_size,
            &materialized.platform,
        )?;
        storage.root = crate::MachineRoot::LinuxOverlay {
            lower: crate::OverlayLower::FlatExt4 {
                stream,
                geometry: vm_spec::DiskGeometry {
                    length: materialized.size_bytes,
                    logical_sector_size: 512,
                },
                filesystem_uuid: lower_uuid,
            },
            upper: crate::PrivatePath::new("upper.raw")?,
            upper_uuid: formatted.uuid,
            capacity: root_disk_size,
            ext4_profile: crate::Ext4Profile::SiloUpperExt4V1,
            overlay_profile: crate::OverlayProfile::SiloOverlayV1,
            temporary_directory: request.temporary_directory,
        };
        storage.profile = crate::StorageProfile::LinuxOverlayV1;
        storage.backend = crate::BackendRequirement::KrunOverlay;
        if let crate::BootProfile::LinuxDirect { root_selector, .. } = &mut storage.boot {
            *root_selector = crate::RootSelector::ManagedOverlay;
        }
        storage.validate()?;
        (rootfs_path, Some(storage))
    } else {
        let rootfs_path = create.dir().join(root_disk_relative_path());
        let source = crate::storage::stream::open_regular_source(&materialized.rootfs_path)?;
        source.sync_all()?;
        let directory = OwnedDirectory::open_existing_root(create.dir())?.ok_or_else(|| {
            crate::machine::root_storage::invalid("new machine directory disappeared")
        })?;
        let stage_name = format!(".copy-{}", uuid::Uuid::new_v4());
        let stage = directory.create_dir(&stage_name)?.ok_or_else(|| {
            crate::machine::root_storage::invalid("private copy staging collision")
        })?;
        let mut qualification = CopyQualification::new(32);
        let mut prepared = copy_private(
            crate::machine::root_disk::CopySource::Unscanned {
                file: &source,
                length: materialized.size_bytes,
            },
            stage,
            "content",
            &mut qualification,
        )?;
        tracing::debug!(
            method = ?prepared.method(),
            verification = ?prepared.verification(),
            file = ?prepared.file(),
            length = materialized.size_bytes,
            "prepared private root copy",
        );
        prepared.publish(directory.try_clone()?, "root.raw")?;
        prepared.retain();
        directory.remove_tree(&stage_name)?;
        directory.sync()?;
        if let Some(size_bytes) = request.disk_size_bytes {
            resize_raw_disk(&rootfs_path, size_bytes)?;
        }
        (rootfs_path, None)
    };
    if let Some(disks) = create
        .spec
        .storage
        .as_mut()
        .map(|storage| &mut storage.disks)
    {
        for disk in disks {
            match disk.role {
                vm_spec::DiskRole::RootLower => disk.geometry.length = materialized.size_bytes,
                vm_spec::DiskRole::Root | vm_spec::DiskRole::RootUpper => {
                    disk.geometry.length = root_disk_size
                }
                vm_spec::DiskRole::Data => {}
            }
        }
    }
    write_machine_config(create.dir(), &create.name, &create.spec)?;

    let rootfs = machine_rootfs_record(&create, &materialized, rootfs_path, root_disk_size);
    create
        .commit(
            runtime,
            rootfs,
            materialized.requested_reference,
            &materialized.platform,
            storage,
            materialized._lease,
        )
        .await
}

async fn create_machine_guard(
    runtime: &Runtime,
    plan: MachineCreatePlan,
    stopped_operation: Option<uuid::Uuid>,
) -> Result<MachineCreateGuard, LibVmError> {
    let MachineCreatePlan {
        name,
        spec,
        labels,
        metadata,
        network,
        guest,
        retention,
        process,
        template_name,
        agent_mode,
    } = plan;

    validate_machine_name(&name)?;

    if runtime
        .machine_config_by_name(name.as_str())
        .await?
        .is_some()
    {
        return Err(LibVmError::MachineAlreadyExists { name });
    }

    let id = match stopped_operation {
        Some(operation) => runtime
            .native_store()?
            .reserved_fork_machine(operation, &name)
            .await?
            .unwrap_or_else(MachineId::new),
        None => MachineId::new(),
    };
    let machine_dir = runtime.machine_paths(id).dir().to_path_buf();
    let lock = runtime.allocate_machine_lock()?;
    let mut create = MachineCreateGuard {
        id,
        name,
        spec,
        machine_dir,
        lock: Some(lock),
        labels,
        metadata,
        network,
        guest,
        retention,
        process,
        template_name,
        agent_mode,
        machine_parent: None,
        preserve: false,
        secret_store: runtime.secret_store_arc(),
    };

    create.create_machine_dir(runtime)?;
    if let Some(operation) = stopped_operation {
        runtime
            .native_store()?
            .preserve_stopped_operation(operation, create.id)
            .await?;
    }
    crate::ssh_ca::resolve(runtime.secret_store(), id, true).map_err(|error| {
        LibVmError::MachinePreparationFailed {
            reference: create.name.clone(),
            message: format!("create machine SSH CA: {error}"),
        }
    })?;
    write_machine_config(create.dir(), &create.name, &create.spec)?;

    Ok(create)
}

fn assign_mount_tags(mounts: Vec<Mount>) -> Vec<Mount> {
    mounts
        .into_iter()
        .enumerate()
        .map(|(index, mut mount)| {
            if mount.tag.trim().is_empty() {
                mount.tag = format!("mount{index}");
            }
            mount
        })
        .collect()
}

fn build_kernel_cmdline(kernel_args: Vec<String>) -> Vec<String> {
    let mut cmdline = vec![ROOT_DISK_KERNEL_ARG.to_string()];
    cmdline.extend(kernel_args);
    cmdline
}

fn canonicalize_existing_paths(paths: &[PathBuf], kind: &str) -> Result<Vec<PathBuf>, LibVmError> {
    paths
        .iter()
        .map(|path| canonicalize_existing_path(path, kind))
        .collect()
}

fn canonicalize_existing_path(path: &Path, kind: &str) -> Result<PathBuf, LibVmError> {
    let abs = if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir()?.join(path)
    };

    std::fs::canonicalize(&abs).map_err(|err| LibVmError::InvalidCreateRequest {
        name: kind.to_string(),
        reason: format!("{kind} path does not exist: {} ({err})", abs.display()),
    })
}

